-- Matchmaker: the questionnaire log, deduplicated impressions, the notify-me
-- capture, and the counters that stop all three being a flood.
--
-- Owner: matchmaker
--
-- Forward-only and additive: see db/README.md. No down migration exists.
--
-- ARCHITECTURE.md, "Database schema -- table ownership", gives this module
-- `match_queries`, `match_impressions` and `notify_requests`. The fourth table
-- here, `matchmaker_rate_limit_events`, is a counter table and not a domain
-- table: `moderation` added `moderation_rate_limit_events` for the same reason
-- and wrote down why -- no module writes another module's tables, so a module
-- with a rate-limited anonymous surface owns its own counters. Reported to the
-- lead architect rather than assumed.
--
-- FIVE DECISIONS WORTH ARGUING WITH
--
-- M1. NOTHING IN THIS FILE IS A RANKING INPUT.
--     art-matchmaker: "The system SHALL NOT use match impression counts, view
--     counts, or any other visitor-influenced value as a ranking input, because
--     an anonymous visitor could otherwise move a rival's position by scripting
--     queries" (SECURITY.md S2-23). Every row in `match_impressions` is written
--     by an anonymous stranger, so the ranking function never reads this table.
--     Rotation within a tie band is a deterministic function of the rotation
--     epoch and the artwork id, which no visitor can influence at all. The
--     tables here are reporting and abuse control; the ranking reads
--     `artworks` and `artwork_embeddings` and nothing else.
--
-- M2. IMPRESSIONS ARE DEDUPLICATED BY THE DATABASE, NOT BY THE APPLICATION.
--     SECURITY.md S2-23 item 1: "at most one impression per artwork per
--     (session or hashed IP) per configured window. Repeated identical queries
--     do not accumulate." A select-then-insert implements that until two
--     requests arrive at once, and the flood this defends against is precisely
--     concurrent. So the window is reified as `dedupe_bucket` -- the window
--     index the application computes from the configured window length -- and a
--     UNIQUE constraint over (artwork, viewer, bucket) makes a second insert in
--     the same window impossible rather than unlikely. The write is
--     `on conflict do nothing`.
--
-- M3. THE ARTIST'S DASHBOARD COUNT DOES NOT COME THROUGH THE DATA API.
--     SECURITY.md's RLS matrix gives `match_impressions` "artist sees own
--     artworks' counts" for `authenticated`. This migration is STRICTER: no
--     grant and no policy for `authenticated` at all. ARCHITECTURE.md, "RLS
--     cannot hide a column": a policy letting an artist read the rows for their
--     own artworks lets them read EVERY COLUMN of those rows, including
--     `viewer_fingerprint`. That column is a stable per-window hash of a
--     visitor, so an artist could learn how many distinct clients saw a piece,
--     when, and -- correlated against their own referral traffic -- plausibly
--     who. The dashboard needs a COUNT, which the server already computes and
--     hands to `artworks.artistDashboard` through the `ImpressionSource` port.
--     A count is not a row, and only the count leaves the server.
--
-- M4. `anon` GETS NO INSERT GRANT, WHICH IS AGAIN STRICTER THAN THE MATRIX.
--     The matrix says "anon INSERT, rate-limited" for `match_queries` and
--     `notify_requests`. Rate limiting counts prior attempts in another table
--     and decides; an RLS policy cannot do that. An anon INSERT grant on the
--     data API would therefore be exactly the flood SECURITY.md S2-22 and S2-21
--     require be refused, arriving on the one path where nothing counts it.
--     Both surfaces go through the server. `moderation` made this same call for
--     `reports` and argued it at length; this is that precedent applied to the
--     two anonymous write surfaces that remain.
--
-- M5. THE NOTIFY-ME CAPTURE IS ONE ROW PER ADDRESS, UPSERTED.
--     art-matchmaker: "the response is identical both times and does not
--     disclose that the address was already stored", and SECURITY.md S2-21 item
--     4 requires double opt-in with "one confirmation email per address per
--     window" and "an unsubscribe token that is random and not derived from the
--     address". A unique index on the normalised address is what makes twenty
--     submissions one row; `confirmation_sent_at` is what makes them one email;
--     and both tokens are generated by `gen_random_bytes` on the server, so
--     neither can be computed from an address an attacker guesses.

-- ---------------------------------------------------------------------------
-- 1. The questionnaire log
-- ---------------------------------------------------------------------------
--
-- Kept because notify-me stores "the answers with the address" (art-matchmaker)
-- and because an operator tuning the scoring weights has nothing else to tune
-- against. Retention is bounded (SECURITY.md S2-22 item 3): a row not
-- referenced by a `notify_requests` entry is swept after the configured window.
-- SECURITY.md is blunt about what these rows are -- "a buyer's budget, home
-- dimensions, and, for notify-me, their email. That is a profile of a
-- household" -- which is why nothing but the server can read them.

create table match_queries (
  id                 uuid        primary key default gen_random_uuid(),

  -- Budget is the one required answer (art-matchmaker, "Buyer questionnaire"),
  -- in agorot, in a bigint, because ARCHITECTURE.md permits no other
  -- representation of money. The minimum is optional: a buyer who states only a
  -- ceiling has stated a budget.
  budget_min_agorot  bigint      check (budget_min_agorot is null or budget_min_agorot >= 0),
  budget_max_agorot  bigint      not null check (budget_max_agorot > 0),

  -- The space available, in whole millimetres, matching `artworks`' own unit.
  -- Optional, like every answer except budget.
  wall_height_mm     integer     check (wall_height_mm is null or wall_height_mm between 1 and 100000),
  wall_width_mm      integer     check (wall_width_mm  is null or wall_width_mm  between 1 and 100000),

  -- The taxonomy answers, validated against the closed set before they get
  -- here (SECURITY.md S2-22 item 5) and constrained again in the database, so a
  -- value nobody can score against is impossible rather than merely unlikely.
  -- The value lists are `artworks`' taxonomy, restated here for the same reason
  -- that module restates them: a check constraint cannot reference another
  -- table's constraint.
  medium             text        check (medium is null or medium in (
                                   'painting_illustration', 'photography',
                                   'ceramics_objects', 'jewelry', 'textile_clothing'
                                 )),
  styles             text[]      not null default '{}'
                                 check (styles <@ array[
                                   'minimalist', 'abstract', 'boho_coastal',
                                   'modern_industrial', 'pop_art'
                                 ]::text[]),
  target_spaces      text[]      not null default '{}'
                                 check (target_spaces <@ array[
                                   'living_room', 'bedroom', 'office_clinic',
                                   'childrens_room', 'kitchen'
                                 ]::text[]),
  moods              text[]      not null default '{}'
                                 check (moods <@ array[
                                   'calm', 'bold', 'romantic', 'edgy'
                                 ]::text[]),

  -- The palette question. A closed set owned by this module, because `artworks`
  -- has no colour column: `uploads` keeps the artist's chosen palette in its
  -- event log. See the header of src/modules/matchmaker/palette.ts for what
  -- that costs and what is not built because of it.
  palette            text        check (palette is null or palette in (
                                   'warm', 'cool', 'neutral', 'earthy',
                                   'monochrome', 'vivid'
                                 )),

  -- A salted hash of whatever identified the client, never the client itself.
  -- SECURITY.md's log-redaction rule puts raw client IPs on the never-stored
  -- list; unhashed, this column turns the questionnaire log into a record of
  -- which address is furnishing which room to what budget.
  client_fingerprint text        not null check (length(client_fingerprint) = 64),

  -- How many matches the buyer was actually shown. Reporting only: it is what
  -- lets an operator answer "how often does the sparse-catalog message fire"
  -- without re-running anyone's questionnaire.
  result_count       integer     not null default 0 check (result_count >= 0),

  created_at         timestamptz not null default now()
);

comment on table match_queries is
  'One submitted questionnaire. A profile of a household (SECURITY.md S2-22): server-only in both directions, retention-bounded, and never a ranking input.';
comment on column match_queries.client_fingerprint is
  'Salted SHA-256 of the client identifier. Never the raw IP (SECURITY.md log redaction, S3-30).';

-- The retention sweep reads by age; nothing else reads this table in bulk.
create index match_queries_created_at_idx on match_queries (created_at);

-- ---------------------------------------------------------------------------
-- 2. Impressions -- reporting only, deduplicated by construction
-- ---------------------------------------------------------------------------

create table match_impressions (
  id                 bigint      generated always as identity primary key,

  artwork_id         uuid        not null references artworks (id) on delete cascade,

  -- The session or hashed IP the impression is attributed to. Hashed for the
  -- same reason as everywhere else in this schema.
  viewer_fingerprint text        not null check (length(viewer_fingerprint) = 64),

  -- The dedupe window this impression falls in, computed by the application
  -- from `matchmaker.impression_dedupe_window_minutes` as
  -- floor(epoch_seconds / (window * 60)). Reified as a column so the UNIQUE
  -- constraint below can enforce "one per window" in the database rather than
  -- in a select-then-insert that loses the race it exists to win. See M2.
  dedupe_bucket      bigint      not null,

  occurred_at        timestamptz not null default now(),

  constraint match_impressions_one_per_viewer_per_window
    unique (artwork_id, viewer_fingerprint, dedupe_bucket)
);

comment on table match_impressions is
  'Deduplicated match impressions, for the artist dashboard and admins. NEVER read by the ranking function (art-matchmaker; SECURITY.md S2-23).';
comment on column match_impressions.dedupe_bucket is
  'Window index. The UNIQUE constraint over (artwork, viewer, bucket) is what makes repeated identical queries fail to accumulate.';

-- The dashboard reads counts for one artist's artworks at a time.
create index match_impressions_artwork_idx on match_impressions (artwork_id);
-- The anomaly report (SECURITY.md S2-23 item 3) reads recent activity.
create index match_impressions_occurred_at_idx on match_impressions (occurred_at desc);

-- ---------------------------------------------------------------------------
-- 3. Notify-me
-- ---------------------------------------------------------------------------

create table notify_requests (
  id                    uuid        primary key default gen_random_uuid(),

  -- Normalised (trimmed, lower-cased) by the application before it arrives, and
  -- unique, which is what makes twenty submissions of one address one row. See
  -- M5. Not hashed: the whole purpose of the row is to send mail to it, and a
  -- hash cannot be mailed. Protected by having no grant instead.
  email                 text        not null
                                    check (length(email) between 3 and 254 and email = lower(btrim(email))),

  -- The answers this buyer wants to be notified about. `set null` rather than
  -- `cascade`: a swept questionnaire must not take the subscription with it,
  -- and the retention sweep is written to skip referenced rows anyway
  -- (SECURITY.md S2-22 item 3). Belt and braces.
  match_query_id        uuid        references match_queries (id) on delete set null,

  -- Double opt-in (SECURITY.md S2-21 item 4). No message is sent to an address
  -- until it has confirmed, which is what stops this endpoint being a mail
  -- cannon aimed at an address the submitter does not own.
  confirmation_token    text        not null check (length(confirmation_token) = 64),
  confirmed_at          timestamptz,

  -- One confirmation email per address per window. The column is what the
  -- throttle reads; the rate limiter is what refuses the twenty-first attempt.
  confirmation_sent_at  timestamptz,

  -- Random, and NOT derived from the address, so it cannot be computed for
  -- someone else's subscription (SECURITY.md S2-21 item 4).
  unsubscribe_token     text        not null unique check (length(unsubscribe_token) = 64),
  unsubscribed_at       timestamptz,

  created_at            timestamptz not null default now(),
  updated_at            timestamptz not null default now(),

  constraint notify_requests_email_unique unique (email)
);

comment on table notify_requests is
  'Notify-me subscriptions. One row per address (M5), double opt-in, server-only. A harvest target: no anon or authenticated grant of any kind.';
comment on column notify_requests.unsubscribe_token is
  'Random, never derived from the address (SECURITY.md S2-21 item 4).';

create trigger notify_requests_set_updated_at
  before update on notify_requests
  for each row execute function public.set_updated_at();

-- ---------------------------------------------------------------------------
-- 4. Rate-limit counters
-- ---------------------------------------------------------------------------
--
-- Counted in Postgres, not in memory, for the reason `accounts` and
-- `moderation` both record: the application runs as serverless functions with
-- no shared memory between invocations, so an in-process counter resets on
-- almost every request and limits nothing at all.
--
-- Two buckets, because SECURITY.md's rate-limit table lists two surfaces here:
-- the matchmaker submission (keyed on IP and session) and notify-me (keyed on
-- IP and address). Subjects are hashed so this does not become a directory of
-- every client and every address that has ever touched the questionnaire.

create table matchmaker_rate_limit_events (
  id          bigint      generated always as identity primary key,
  bucket      text        not null check (bucket in ('questionnaire', 'notify')),
  subject     text        not null check (length(subject) = 64),
  occurred_at timestamptz not null default now()
);

comment on table matchmaker_rate_limit_events is
  'Attempt counters for the two anonymous matchmaker surfaces. Recorded whether or not the attempt is allowed, and outside the transaction that does the work, so a refusal still counts.';

create index matchmaker_rate_limit_events_lookup_idx
  on matchmaker_rate_limit_events (bucket, subject, occurred_at desc);

-- ---------------------------------------------------------------------------
-- 5. Row-level security, read and WRITE
-- ---------------------------------------------------------------------------
--
-- ARCHITECTURE.md, "Every table needs write policies, not just read policies":
-- a table with FORCE RLS and only `for select` policies permits no writes
-- except by a role that bypasses RLS, which makes correctness depend on a
-- deployment setting and fails in production while tests stay green. Every
-- role's write side is stated below, and where a role has none, that is said in
-- words rather than left as silence.
--
-- `using (true)` appears on the service_role policies. SECURITY.md's
-- cross-cutting rule forbids it "except on rows that are genuinely public to
-- the internet"; the exception taken here is the narrow one `moderation` argued
-- for and is scoped `to service_role`, a role that is server-only by
-- construction. Any narrower predicate would restate a decision the server has
-- already made in code, and a reader would then have to check both. The rule
-- exists to keep `using (true)` away from anon and authenticated, and neither
-- appears anywhere in this file.

alter table match_queries                enable row level security;
alter table match_queries                force  row level security;
alter table match_impressions            enable row level security;
alter table match_impressions            force  row level security;
alter table notify_requests              enable row level security;
alter table notify_requests              force  row level security;
alter table matchmaker_rate_limit_events enable row level security;
alter table matchmaker_rate_limit_events force  row level security;

-- ---- match_queries: server reads, server writes, server sweeps.

create policy match_queries_server_read on match_queries
  for select to service_role
  using (true);

-- A questionnaire always carries a fingerprint and a real budget ceiling. The
-- `with check` restates at write time what the column constraints say at rest,
-- because a row that arrives without a fingerprint is a row the rate limiter
-- cannot account for afterwards.
create policy match_queries_server_insert on match_queries
  for insert to service_role
  with check (length(client_fingerprint) = 64 and budget_max_agorot > 0);

-- UPDATE, service_role only, and only `result_count`: the sweep and the notify
-- link are the only things that touch a submitted questionnaire afterwards, and
-- an answer that could be edited after the fact is not a record of what anyone
-- answered. The predicate cannot name a column list, so it says the part that
-- matters -- the answers on the row as it will be are the answers it had.
create policy match_queries_server_update on match_queries
  for update to service_role
  using (true)
  with check (length(client_fingerprint) = 64 and budget_max_agorot > 0);

-- DELETE: the retention sweep (SECURITY.md S2-22 item 3). Without a delete
-- policy that sweep silently does nothing the moment the connection role stops
-- bypassing RLS, and the storage ceiling the sweep exists to defend is reached
-- anyway.
create policy match_queries_server_sweep on match_queries
  for delete to service_role
  using (true);

-- anon and authenticated: NO POLICY AND NO GRANT, INTENTIONALLY. See M4 for the
-- insert side and SECURITY.md S2-22 item 4 for the read side.

-- ---- match_impressions: server reads and writes; artists get a count, not rows.

create policy match_impressions_server_read on match_impressions
  for select to service_role
  using (true);

create policy match_impressions_server_insert on match_impressions
  for insert to service_role
  with check (length(viewer_fingerprint) = 64);

-- DELETE for the retention sweep. No UPDATE policy for any role: an impression
-- is a fact about a moment, written once and swept, never amended -- and an
-- impression that could be updated is a count that could be edited, which is
-- the reporting number an artist is entitled to trust.
create policy match_impressions_server_sweep on match_impressions
  for delete to service_role
  using (true);

-- anon and authenticated: NO POLICY AND NO GRANT, INTENTIONALLY. See M3.

-- ---- notify_requests: server only, in every direction.

create policy notify_requests_server_read on notify_requests
  for select to service_role
  using (true);

-- A new subscription is never pre-confirmed. Confirmation is something the
-- address holder does; a row that could be inserted already confirmed would let
-- the capture endpoint sign a stranger up for real mail in one request, which
-- is the whole of SECURITY.md S2-21.
create policy notify_requests_server_insert on notify_requests
  for insert to service_role
  with check (
    confirmed_at is null
    and length(confirmation_token) = 64
    and length(unsubscribe_token) = 64
    and email = lower(btrim(email))
  );

-- UPDATE: re-submission refreshes the stored answers, confirmation stamps
-- `confirmed_at`, unsubscribe stamps `unsubscribed_at`. The address itself and
-- the unsubscribe token are immutable, enforced by the trigger below rather
-- than by which columns the application happens to name -- the same argument
-- SECURITY.md S1-14 makes for the audit log.
create policy notify_requests_server_update on notify_requests
  for update to service_role
  using (true)
  with check (length(unsubscribe_token) = 64 and email = lower(btrim(email)));

-- DELETE: erasure on request (SECURITY.md S3-30) and the unsubscribe path that
-- chooses to remove rather than tombstone. Server only.
create policy notify_requests_server_delete on notify_requests
  for delete to service_role
  using (true);

-- ---- The counters: server-only in both directions.
--
-- `delete` is a real requirement, not a courtesy: the prune sweeps expired rows,
-- and without a delete policy it silently does nothing the moment the
-- connection role stops bypassing RLS.

create policy matchmaker_rate_limit_events_server_read on matchmaker_rate_limit_events
  for select to service_role
  using (true);

create policy matchmaker_rate_limit_events_server_insert on matchmaker_rate_limit_events
  for insert to service_role
  with check (length(subject) = 64);

create policy matchmaker_rate_limit_events_server_prune on matchmaker_rate_limit_events
  for delete to service_role
  using (occurred_at < now());

-- No UPDATE policy: a counter row is a fact about a moment.

-- ---------------------------------------------------------------------------
-- 6. What cannot be edited after the fact
-- ---------------------------------------------------------------------------
--
-- The address a subscription is for, and the token that unsubscribes it, are
-- fixed when the row is created. Enforced by a trigger so that it holds against
-- every UPDATE anyone ever writes, not only the ones this module ships today.

create schema if not exists matchmaker;
comment on schema matchmaker is
  'Private helpers for the matchmaker module. Not `public`, so nothing here is published as a PostgREST RPC.';

create function matchmaker.notify_request_identity_is_immutable() returns trigger
language plpgsql
set search_path = ''
as $fn$
begin
  if new.email is distinct from old.email
     or new.unsubscribe_token is distinct from old.unsubscribe_token
     or new.created_at is distinct from old.created_at then
    raise exception
      'notify_requests: the address and its unsubscribe token are fixed when the subscription is created'
      using errcode = 'restrict_violation',
            hint = 'Delete the subscription and capture a new one. Do not rewrite an existing address.';
  end if;
  return new;
end
$fn$;

create trigger notify_requests_identity_is_immutable
  before update on notify_requests
  for each row execute function matchmaker.notify_request_identity_is_immutable();

-- ---------------------------------------------------------------------------
-- 7. Grants
-- ---------------------------------------------------------------------------
--
-- Supabase ships ALTER DEFAULT PRIVILEGES granting table privileges to anon and
-- authenticated in `public`, so a new table can arrive already exposed. Every
-- revoke below is stated explicitly rather than left to the default. All four
-- tables hold either a profile of a household, a harvestable address, or a
-- record of which hashed client saw what -- none of it is anyone's business but
-- the server's.

revoke all on match_queries                from public;
revoke all on match_queries                from anon, authenticated;
revoke all on match_impressions            from public;
revoke all on match_impressions            from anon, authenticated;
revoke all on notify_requests              from public;
revoke all on notify_requests              from anon, authenticated;
revoke all on matchmaker_rate_limit_events from public;
revoke all on matchmaker_rate_limit_events from anon, authenticated;

grant select, insert, update, delete on match_queries     to service_role;
grant select, insert, delete         on match_impressions  to service_role;
grant select, insert, update, delete on notify_requests    to service_role;
grant select, insert, delete         on matchmaker_rate_limit_events to service_role;

-- `match_impressions` uses an identity column, which needs no sequence grant in
-- PostgreSQL 10+; the same is true of `matchmaker_rate_limit_events`.
